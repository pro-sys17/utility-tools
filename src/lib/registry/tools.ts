export function getAllTools(): ToolDefinition[] {
  return TOOLS;
}

export function getToolBySlug(slug: string): ToolDefinition | undefined {
  return TOOLS.find((t) => t.slug === slug);
}

export function getToolById(id: string): ToolDefinition | undefined {
  return TOOLS.find((t) => t.id === id);
}

export function getToolsByCategory(category: ToolCategory): ToolDefinition[] {
  return TOOLS.filter((t) => t.category === category);
}

export function getFeaturedTools(): ToolDefinition[] {
  return TOOLS.filter((t) => t.featured && t.status === "active");
}

export function getPopularTools(): ToolDefinition[] {
  return TOOLS.filter((t) => t.popular && t.status === "active");
}

export function getRelatedTools(tool: ToolDefinition, limit: number = 4): ToolDefinition[] {
  return TOOLS.filter((t) => t.id !== tool.id && (t.category === tool.category || t.status === "active")).slice(
    0,
    limit
  );
}

export function searchTools(query: string, category?: string): ToolDefinition[] {
  const q = query.toLowerCase().trim();
  return TOOLS.filter((t) => {
    const matchesCategory = !category || category === "all" || t.category === category;
    if (!matchesCategory) return false;
    if (!q) return true;
    const matchesName = t.name.toLowerCase().includes(q);
    const matchesDesc = t.description.toLowerCase().includes(q);
    const matchesKeywords = t.keywords.some((k) => k.toLowerCase().includes(q));
    return matchesName || matchesDesc || matchesKeywords;
  });
}
